// Renders the screen's fixed Arabic words as PNG images with the Thmanyah font.
//
// The Thmanyah license forbids hosting or web-embedding the font files, so the
// font never enters this repo or the published site: it is read from a local
// folder (THMANYAH_DIR), drawn in the browser, and only the images are saved
// into public/labels/ together with public/labels.js (sizes for layout).
//
// Usage: node tools/render-labels.mjs, then open the printed URL in a browser.
import { createServer } from 'node:http';
import { readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import { join, normalize, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const TOOLS = fileURLToPath(new URL('.', import.meta.url));
const PUBLIC = fileURLToPath(new URL('../public/', import.meta.url));
const OUT = join(PUBLIC, 'labels');
const FONT_DIR = process.env.THMANYAH_DIR ||
  join(process.env.LOCALAPPDATA || '', 'Temp', 'thmanyah', 'thmanyah typeface');
const PORT = Number(process.env.PORT) || 8095;

const manifest = {};

function send(res, status, type, body) {
  res.writeHead(status, { 'Content-Type': type, 'Cache-Control': 'no-store' });
  res.end(body);
}

async function readBody(req) {
  const chunks = [];
  for await (const c of req) chunks.push(c);
  return JSON.parse(Buffer.concat(chunks).toString('utf8'));
}

createServer(async (req, res) => {
  const path = decodeURIComponent(new URL(req.url, 'http://x').pathname);
  try {
    if (req.method === 'GET' && (path === '/' || path === '/render.html')) {
      return send(res, 200, 'text/html; charset=utf-8', await readFile(join(TOOLS, 'render.html')));
    }
    if (req.method === 'GET' && path === '/icon.html') {
      return send(res, 200, 'text/html; charset=utf-8', await readFile(join(TOOLS, 'icon.html')));
    }
    if (req.method === 'POST' && path === '/save-icon') {
      const { png } = await readBody(req);
      await writeFile(join(PUBLIC, 'tile-icon.png'), Buffer.from(png.split(',')[1], 'base64'));
      return send(res, 200, 'application/json', '{"ok":true}');
    }
    if (req.method === 'GET' && path === '/label-catalog.js') {
      return send(res, 200, 'text/javascript; charset=utf-8', await readFile(join(TOOLS, 'label-catalog.js')));
    }
    if (req.method === 'GET' && path.startsWith('/font/')) {
      const file = normalize(join(FONT_DIR, path.slice('/font/'.length)));
      if (!file.startsWith(normalize(FONT_DIR) + sep)) return send(res, 403, 'text/plain', '');
      return send(res, 200, 'font/woff2', await readFile(file));
    }
    if (req.method === 'POST' && path === '/start') {
      await rm(OUT, { recursive: true, force: true });
      await mkdir(OUT, { recursive: true });
      for (const k of Object.keys(manifest)) delete manifest[k];
      return send(res, 200, 'application/json', '{"ok":true}');
    }
    if (req.method === 'POST' && path === '/save') {
      const { key, png, meta } = await readBody(req);
      if (!/^[a-z0-9_]+$/.test(key)) return send(res, 400, 'text/plain', 'bad key');
      await writeFile(join(OUT, key + '.png'), Buffer.from(png.split(',')[1], 'base64'));
      if (meta) manifest[key] = meta;
      return send(res, 200, 'application/json', '{"ok":true}');
    }
    if (req.method === 'POST' && path === '/done') {
      const js = '// Generated by tools/render-labels.mjs. Thmanyah-rendered word images:\n' +
        '// t = text, h = image height in em, d = descent below baseline in em, r = width/height.\n' +
        'window.LABELS = ' + JSON.stringify(manifest, null, 0) + ';\n';
      await writeFile(join(PUBLIC, 'labels.js'), js);
      console.log(`saved ${Object.keys(manifest).length} labels`);
      return send(res, 200, 'application/json', JSON.stringify({ ok: true, count: Object.keys(manifest).length }));
    }
    send(res, 404, 'text/plain', 'not found');
  } catch (e) {
    send(res, 500, 'text/plain', e.message);
  }
}).listen(PORT, '127.0.0.1', () => console.log(`label renderer: http://localhost:${PORT}/`));
